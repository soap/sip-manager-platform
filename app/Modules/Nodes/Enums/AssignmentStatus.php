<?php

namespace App\Modules\Nodes\Enums;

/**
 * Whether a tenant's numbers on its node are in service. A suspended assignment keeps its range,
 * so no other tenant can take the numbers.
 */
enum AssignmentStatus: string
{
    case Active = 'active';
    case Suspended = 'suspended';

    public function label(): string
    {
        return match ($this) {
            self::Active => 'Active',
            self::Suspended => 'Suspended',
        };
    }

    /**
     * @return list<array{value: string, label: string}>
     */
    public static function options(): array
    {
        return array_map(fn (self $status): array => ['value' => $status->value, 'label' => $status->label()], self::cases());
    }
}
